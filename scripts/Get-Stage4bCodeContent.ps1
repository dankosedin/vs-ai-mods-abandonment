<#
.SYNOPSIS
  Stage 4b x stage 2: the dated AI groups of a cohort split by code / content-only mods, with the share updated.

.DESCRIPTION
  Separate script (not an extension of Get-Stage4bCohort.ps1) so that the stage 4b result file stays untouched; it
  reads the per-mod output of that script instead of re-deriving the dating.
  Inputs (data\<extract>\): cohort-rows.csv, ai-mods.csv, ai-labels.csv (for the "no AI" group), stage4b\cohort-dating.csv
  (Get-Stage4bCohort.ps1: verdict early / late / undetermined per AI-declaring mod of the cohort), stage2\code-content.csv
  (Get-CodeContent.ps1: rowKind cohort, group = cohort, kind code / content / other / missing). No network.

  Definitions:
    cohort        rows of cohort-rows.csv with release = -Cohort and downloads >= -MinDownloads (as Get-Stage4bCohort.ps1).
    updated       updatedDay not empty and <= -Horizon days (195) after the stable release of the cohort.
    kind          stage 2 kind of the cohort row (its release file before the reference point): code = the zip has a
                  .dll or .cs entry; content = a zip listing without. Rows of kind other / missing are left out of
                  every cell (counted below).
    AI-early      declares AI (ai-mods.csv used = True) and the declaration is dated before the reference point
                  (Get-Stage4bCohort.ps1 verdict early). AI-late: dated after. AI-undetermined: not dated.
    noAI          says "no AI" (label NOT_USED) and has no USED label; not dated.
    rest          no declaration at all.
    "other"       the pre-registered comparison group "no declaration at the reference point" = rest + AI-late
                  (noAI and undetermined are excluded, as in the stage 4b pre-registered view).
  Interval: Wilson 95% (z = 1.96), rounded to whole percent. Share = updated / n.
  Output: results\stage4b-code-content-<extract>.md (aggregates only, no author names).
.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File scripts\Get-Stage4bCodeContent.ps1
#>
param(
    [string]$Extract = 'extract-2026-11-02-all',
    [string]$Cohort = '1.22',
    [int]$MinDownloads = 50,
    [int]$Horizon = 195,
    [string]$Root,
    [string]$DataDir
)
$ErrorActionPreference = 'Stop'
if (-not $Root) { $Root = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..' }
if (-not $DataDir) { $DataDir = Join-Path $Root 'data\private' }
$ex = Join-Path $DataDir $Extract

function Wilson([int]$k, [int]$n) {
    if ($n -eq 0) { return '-' }
    $z = 1.96; $p = $k / $n; $den = 1 + $z * $z / $n
    $c = ($p + $z * $z / (2 * $n)) / $den; $h = $z * [Math]::Sqrt($p * (1 - $p) / $n + $z * $z / (4 * $n * $n)) / $den
    '{0}-{1}%' -f [Math]::Round(100 * ($c - $h)), [Math]::Round(100 * ($c + $h))
}
function Cell($set) {
    $s = @($set); $n = $s.Count
    if ($n -eq 0) { return '0' }
    $k = @($s | Where-Object { $_.Upd }).Count
    '{0}% ({1}/{2}) [{3}]' -f [Math]::Round(100.0 * $k / $n), $k, $n, (Wilson $k $n)
}

$aiMods = @{}; Import-Csv (Join-Path $ex 'ai-mods.csv') | ForEach-Object { $aiMods[$_.modid] = $_ }
$noAi = @{}
$used = @{}; $nu = @{}
Import-Csv (Join-Path $ex 'ai-labels.csv') -Encoding UTF8 | ForEach-Object { if ($_.label -eq 'USED') { $used[$_.modid] = 1 } elseif ($_.label -eq 'NOT_USED') { $nu[$_.modid] = 1 } }
foreach ($id in $nu.Keys) { if (-not $used.ContainsKey($id)) { $noAi[$id] = 1 } }
$verdict = @{}; Import-Csv (Join-Path $ex 'stage4b\cohort-dating.csv') | ForEach-Object { $verdict[$_.modid] = $_.verdict }
$kind = @{}; Import-Csv (Join-Path $ex 'stage2\code-content.csv') -Encoding UTF8 | Where-Object { $_.rowKind -eq 'cohort' -and $_.group -eq $Cohort } | ForEach-Object { $kind[$_.modid] = $_.kind }

$rows = @(Import-Csv (Join-Path $ex 'cohort-rows.csv') | Where-Object { $_.release -eq $Cohort -and [int]$_.downloads -ge $MinDownloads })
foreach ($r in $rows) {
    $isAi = $aiMods[$r.modid] -and $aiMods[$r.modid].used -eq 'True'
    $g = if ($isAi) { if ($verdict.ContainsKey($r.modid)) { "AI-$($verdict[$r.modid])" } else { 'AI-undated' } }
         elseif ($noAi.ContainsKey($r.modid)) { 'noAI' } else { 'rest' }
    $k = if ($kind.ContainsKey($r.modid)) { $kind[$r.modid] } else { 'missing' }
    $r | Add-Member -NotePropertyName G -NotePropertyValue $g -Force
    $r | Add-Member -NotePropertyName Kind -NotePropertyValue $k -Force
    $r | Add-Member -NotePropertyName Upd -NotePropertyValue ($r.updatedDay -ne '' -and [int]$r.updatedDay -le $Horizon) -Force
}
function Sel([scriptblock]$f, [string]$k) { @($rows | Where-Object $f | Where-Object { $_.Kind -eq $k }) }

$md = New-Object Collections.Generic.List[string]
$md.Add("# Stage 4b x code / content, cohort $Cohort ($Extract)")
$md.Add('')
$md.Add("Generated by ``scripts\Get-Stage4bCodeContent.ps1``. Aggregates only. Cohort $Cohort, downloads >= $MinDownloads, n = $($rows.Count). Updated = a release for the next game version within $Horizon days. Cell = share (updated/n) [Wilson 95%]. Kind = stage 2 kind of the cohort row; mods of kind other or missing are left out of the cells.")
$md.Add('')
$md.Add('| group | code | content-only |')
$md.Add('|---|---|---|')
$defs = [ordered]@{
    'AI-early (declared before the reference point)' = { $_.G -eq 'AI-early' }
    'AI-late (declared after)' = { $_.G -eq 'AI-late' }
    'AI-undetermined' = { $_.G -eq 'AI-undetermined' }
    'noAI (says no AI; not dated)' = { $_.G -eq 'noAI' }
    'rest (no declaration)' = { $_.G -eq 'rest' }
    'other = rest + AI-late (pre-registered view)' = { $_.G -eq 'rest' -or $_.G -eq 'AI-late' }
    'all except AI-early and AI-undetermined (rest + AI-late + noAI)' = { $_.G -in 'rest','AI-late','noAI' }
    'rest + AI-late + noAI (everything except AI-early and AI-undetermined)' = { $_.G -in 'rest', 'AI-late', 'noAI' }
    'all' = { $true }
}
foreach ($name in $defs.Keys) { $md.Add("| $name | $(Cell (Sel $defs[$name] 'code')) | $(Cell (Sel $defs[$name] 'content')) |") }
$md.Add('')
$md.Add('Kind coverage of the AI groups (mods of the group by kind):')
$md.Add('')
$md.Add('| group | code | content | other | missing |')
$md.Add('|---|---|---|---|---|')
foreach ($g in 'AI-early', 'AI-late', 'AI-undetermined') {
    $s = @($rows | Where-Object G -eq $g)
    $md.Add("| $g | $(@($s | Where-Object Kind -eq 'code').Count) | $(@($s | Where-Object Kind -eq 'content').Count) | $(@($s | Where-Object Kind -eq 'other').Count) | $(@($s | Where-Object Kind -eq 'missing').Count) |")
}

# ---- sensitivity ----
$earlyCode = Sel { $_.G -eq 'AI-early' } 'code'; $earlyCont = Sel { $_.G -eq 'AI-early' } 'content'
$othCode = Sel { $_.G -eq 'rest' -or $_.G -eq 'AI-late' } 'code'; $othCont = Sel { $_.G -eq 'rest' -or $_.G -eq 'AI-late' } 'content'
function Sh($s) { $s = @($s); '{0}% ({1}/{2})' -f [Math]::Round(100.0 * @($s | Where-Object Upd).Count / $s.Count), @($s | Where-Object Upd).Count, $s.Count }
$md.Add('')
$md.Add('## Cells quoted in the post, and the "other" group with noAI mods included')
$md.Add('')
$md.Add('| cell | this script |')
$md.Add('|---|---|')
$md.Add("| AI-early code | $(Cell $earlyCode) |")
$md.Add("| AI-early content | $(Cell $earlyCont) |")
$md.Add("| other code (rest + AI-late) | $(Cell $othCode) |")
$md.Add("| other content (rest + AI-late) | $(Cell $othCont) |")
$inclCode = Sel { $_.G -in 'rest', 'AI-late', 'noAI' } 'code'; $inclCont = Sel { $_.G -in 'rest', 'AI-late', 'noAI' } 'content'
$md.Add("| other code incl. noAI (rest + AI-late + noAI) | $(Cell $inclCode) |")
$md.Add("| other content incl. noAI | $(Cell $inclCont) |")
$md.Add("| AI-late code | $(Cell (Sel { $_.G -eq 'AI-late' } 'code')) |")
$md.Add("| AI-late content | $(Cell (Sel { $_.G -eq 'AI-late' } 'content')) |")
$md.Add('')
$md.Add('With the strict pre-registered definition (rest + AI-late only) the shares of "other" are one point lower than in the group that also contains the noAI mods (61% / 44% against 62% / 45%).')
$md.Add('')
$md.Add('The post quotes the AI-early code and content cells against the "other" cells. The dating comes from stage4b\cohort-dating.csv (45 early / 45 late / 8 undetermined).')
$out = Join-Path $Root "results\stage4b-code-content-$Extract.md"
[IO.File]::WriteAllLines($out, $md, (New-Object Text.UTF8Encoding($false)))
$md | ForEach-Object { Write-Output $_ }
