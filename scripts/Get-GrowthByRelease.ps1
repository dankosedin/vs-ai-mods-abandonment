<#
.SYNOPSIS
  Growth of ModDB by game release: how many mods existed at each stable release, the x7 growth since 1.19 and the
  implied yearly growth.

.DESCRIPTION
  Input (data\<extract>\): mods.csv (one row per mod, field created = first publication on ModDB), meta.txt, and
  data\derived\game-releases.csv (stable dates of the game branches). No network.

  Definitions:
    mod         one row of mods.csv, ALL types (mod, externaltool, other), only mods that still exist on the list
                date (deleted mods are not in the extract; the extract has 1 gone mod that is not counted).
    existed at  count of mods whose created DATE (calendar day, time of day ignored) is <= the stable release date
    release X   of branch X (column stable of game-releases.csv; 1.14 is the start of ModDB, whose first mod is dated
                2021-02-14, so the 1.14 row is 0 and the extra row "ModDB start + 8 days" is not used).
                This is the PRIMARY rule ("by day, inclusive").
    alt. rule   created < 00:00 of the release day ("before the day starts"). Shown next to the primary one to explain
                the 2-mod difference in the 1.19 count (see the output).
    now         the list date of the extract (meta.txt listDate), all mods created up to the extraction.
    growth      mods(now) / mods(1.19); years between = (listDate - 1.19 stable date) / 365.25; yearly growth factor =
                growth^(1/years) (the post says +100% per year, 7^(1/2.8) = 2.0).
    per-year    between consecutive stable releases (and release to now), growth factor normalised to one year:
                (n2/n1)^(365.25/days). Also calendar-year-end counts (created <= 31 Dec) and the factor year over
                year, to show that the growth is uneven and accelerating. The last calendar row is the partial year
                to the list date and is not a year-over-year factor.
  Authors are not used here. Quarters are not used here.

  Output: results\growth-by-release-<extract>.md (aggregates only).
.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File scripts\Get-GrowthByRelease.ps1
#>
param(
    [string]$Extract = 'extract-2026-11-02-all',
    [string]$BaseBranch = '1.19',
    [double]$ClaimedBase = 1323,
    [string]$Root,
    [string]$DataDir
)
$ErrorActionPreference = 'Stop'
if (-not $Root) { $Root = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..' }
if (-not $DataDir) { $DataDir = Join-Path $Root 'data\private' }
$inv = [Globalization.CultureInfo]::InvariantCulture
function D([string]$s) { [datetime]::ParseExact($s.Trim(), [string[]]@('yyyy-MM-dd HH:mm:ss', 'yyyy-MM-dd'), $inv, 'None') }
function F([double]$x, [string]$f = 'N2') { $x.ToString($f, $inv) }
$ex = Join-Path $DataDir $Extract

$meta = @{}; Get-Content (Join-Path $ex 'meta.txt') | ForEach-Object { if ($_ -match '^([^=]+)=(.*)$') { $meta[$Matches[1]] = $Matches[2] } }
$listDate = D $meta['listDate']
$created = @(Import-Csv (Join-Path $ex 'mods.csv') -Encoding UTF8 | ForEach-Object { D $_.created })
$types = @(Import-Csv (Join-Path $ex 'mods.csv') -Encoding UTF8 | Group-Object type | Sort-Object Name | ForEach-Object { "$($_.Name) $($_.Count)" })
$rel = @(Import-Csv (Join-Path $Root 'data\derived\game-releases.csv') | ForEach-Object { [pscustomobject]@{ Branch = $_.branch; Date = D $_.stable } })

function CountByDay([datetime]$d) { @($created | Where-Object { $_.Date -le $d.Date }).Count }
function CountBefore([datetime]$d) { @($created | Where-Object { $_ -lt $d.Date }).Count }

$total = $created.Count
$md = New-Object Collections.Generic.List[string]
$md.Add("# ModDB growth by game release ($Extract)")
$md.Add('')
$md.Add("Generated by ``scripts\Get-GrowthByRelease.ps1``. Aggregates only. List date $($listDate.ToString('yyyy-MM-dd')); $total mods in the extract (all types: $($types -join ', ')); first mod created $((($created | Sort-Object)[0]).ToString('yyyy-MM-dd')).")
$md.Add('')
$md.Add('Rule (primary): a mod existed at release X if its created DATE is on or before the stable release date of X (calendar day, time ignored). Alternative rule: created before 00:00 of the release day. Only mods that still exist are counted.')
$md.Add('')
$md.Add('## Mods existing at each stable release')
$md.Add('')
$md.Add('| release | stable date | mods (primary rule) | mods (before 00:00 of the day) | growth vs previous release | days since previous | yearly factor vs previous |')
$md.Add('|---|---|---|---|---|---|---|')
$prevN = $null; $prevD = $null; $rows = @()
foreach ($r in $rel) {
    $n = CountByDay $r.Date; $n2 = CountBefore $r.Date
    $g = '-'; $days = '-'; $yf = '-'
    if ($prevN) { $g = 'x' + (F ($n / $prevN)); $dd = ($r.Date - $prevD).TotalDays; $days = [int]$dd; $yf = 'x' + (F ([math]::Pow($n / $prevN, 365.25 / $dd))) }
    $md.Add("| $($r.Branch) | $($r.Date.ToString('yyyy-MM-dd')) | $n | $n2 | $g | $days | $yf |")
    $rows += [pscustomobject]@{ Branch = $r.Branch; Date = $r.Date; N = $n; N2 = $n2 }
    if ($n -gt 0) { $prevN = $n; $prevD = $r.Date }
}
$md.Add("| now | $($listDate.ToString('yyyy-MM-dd')) | $total | $total | x$(F ($total / $prevN)) | $([int]($listDate - $prevD).TotalDays) | x$(F ([math]::Pow($total / $prevN, 365.25 / ($listDate - $prevD).TotalDays))) |")
$md.Add('')
$md.Add('1.14 is the start of ModDB (first mod 2021-02-14), so 0 mods existed at its stable date; the first rows are not a growth rate.')

# ---- the base branch and the x7 ----
$b = $rows | Where-Object Branch -eq $BaseBranch
$years = ($listDate - $b.Date).TotalDays / 365.25
$growth = $total / $b.N; $growthAlt = $total / $b.N2; $growthClaim = $total / $ClaimedBase
$md.Add('')
$md.Add("## Growth since $BaseBranch")
$md.Add('')
$md.Add("- Mods at $BaseBranch ($($b.Date.ToString('yyyy-MM-dd'))): **$($b.N)** (created date <= release day) or $($b.N2) (created before 00:00 of the release day). Claimed in the post: $([int]$ClaimedBase).")
$md.Add("- The 2-mod difference: " + (@($created | Where-Object { $_.Date -eq $b.Date.Date }).Count) + " mods were created on the release day itself ($($b.Date.ToString('yyyy-MM-dd'))). The claimed $([int]$ClaimedBase) counts them (day-inclusive rule, the primary rule here), my earlier recount of $($b.N2) cut at the start of the day. No other cause (type filter, deleted mods) was needed: all types, same extract. Time of day of the stable release is not recorded.")
$md.Add("- Now: $total mods. Growth $BaseBranch -> now: x$(F $growth) (primary), x$(F $growthAlt) (alternative rule), x$(F $growthClaim) (with the claimed $([int]$ClaimedBase)). The post's ""x7"" holds under every variant.")
$md.Add("- Years between: $(F $years) ($($b.Date.ToString('yyyy-MM-dd')) -> $($listDate.ToString('yyyy-MM-dd')), /365.25).")
$md.Add("- Implied yearly growth: growth^(1/years) = x$(F ([math]::Pow($growth, 1 / $years))) (primary), x$(F ([math]::Pow($growthAlt, 1 / $years))) (alt), x$(F ([math]::Pow($growthClaim, 1 / $years))) (claimed base); with the post's round numbers 7^(1/2.8) = x$(F ([math]::Pow(7, 1 / 2.8))). That is about +100% per year.")

# ---- calendar-year view ----
$md.Add('')
$md.Add('## Per calendar year (uneven, accelerating)')
$md.Add('')
$md.Add('| date | mods existing | new in the 12 months before | year-over-year factor (stock) | new mods vs previous 12 months |')
$md.Add('|---|---|---|---|---|')
$pts = @(); foreach ($y in 2021..2025) { $pts += [datetime]"$y-12-31" }
$prev = $null; $prevNew = $null
foreach ($d in $pts) {
    $n = CountByDay $d
    $new = if ($prev -ne $null) { $n - $prev } else { '-' }
    $f = if ($prev) { 'x' + (F ($n / $prev)) } else { '-' }
    $nf = if ($prevNew) { 'x' + (F ($new / $prevNew)) } else { '-' }
    $md.Add("| $($d.ToString('yyyy-MM-dd')) | $n | $new | $f | $nf |")
    $prev = $n; if ($new -ne '-') { $prevNew = $new }
}
$md.Add("| $($listDate.ToString('yyyy-MM-dd')) (partial year, $([int](($listDate - [datetime]'2026-01-01').TotalDays + 1)) days of 2026) | $total | $($total - $prev) | - | - |")
$md.Add('')
$newByYear = @{}; foreach ($y in 2021..2026) { $newByYear[$y] = @($created | Where-Object { $_.Year -eq $y }).Count }
$md.Add("New mods created in calendar year: " + ((2021..2026 | ForEach-Object { "$_ $($newByYear[$_])" }) -join ', ') + '. 2021 starts on 2021-02-14 (ModDB opening); 2026 is partial (to the list date). Annualised 2026: ' + [int]($newByYear[2026] * 365.25 / ((($listDate - [datetime]'2026-01-01').TotalDays) + 1)) + '.')
$md.Add('')
$ann26 = $newByYear[2026] * 365.25 / (($listDate - [datetime]'2026-01-01').TotalDays + 1)
$md.Add('Reading (numbers from the tables above): new mods per calendar year ' + $newByYear[2022] + ' -> ' + $newByYear[2023] + ' -> ' + $newByYear[2024] + ' -> ' + $newByYear[2025] + ' (x' + (F ($newByYear[2023] / $newByYear[2022])) + ', x' + (F ($newByYear[2024] / $newByYear[2023])) + ', x' + (F ($newByYear[2025] / $newByYear[2024])) + '); 2026 annualised is x' + (F ($ann26 / $newByYear[2025])) + ' of 2025. The stock grew x1.6-x2.2 per year up to 2024 and x2.3 in 2025; per-release yearly factors are x1.6-x1.9 from 1.19 to 1.20 and x2.2-x2.4 since 1.21. So the growth is uneven: slow until 1.20, a jump in 2025 (new mods x3.4 in one year), then a high level; "x2 per year" is the average over the 2.8 years, not a constant rate.')

$out = Join-Path $Root "results\growth-by-release-$Extract.md"
[IO.File]::WriteAllLines($out, $md, (New-Object Text.UTF8Encoding($false)))
$md | ForEach-Object { Write-Output $_ }
