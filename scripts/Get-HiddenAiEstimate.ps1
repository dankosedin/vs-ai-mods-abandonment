<#
.SYNOPSIS
  Reproduces the "hidden AI" estimates of the post from the extract: repository traces among mods that do not declare
  AI, corrected by the sensitivity of the traces; and the tipping-point check.

.DESCRIPTION
  Inputs (data\<extract>\): mods.csv, releases.csv, ai-mods.csv, cohort-rows.csv, stage3\mod-repo-ai.csv
  (Find-RepoAiTraces.ps1, one row per mod with a scanned repository), stage4b\cohort-dating.csv. No network.

  Definitions:
    declared        ai-mods.csv used = True (current texts).      noAI  notUsed = True and used is not True.
    repo mod        a mod with a row in stage3\mod-repo-ai.csv with status ok (readable repository).
    trace           aiTrace = yes (AI trailer, file, message, branch or agent author in the repository history);
                    firstAiDate = date of the earliest trace.
    undeclared      not declared and not noAI ("silent" mods).
    sensitivity     share of DECLARED repo mods that show a trace = traced / declared repo mods (all years, any trace
                    date). The post uses ~45%. It is measured on authors who declare, so it is only a rough guide to
                    authors who do not.
    corrected share observed share / sensitivity.
  Claims reproduced:
    #51  cohort 1.22 (downloads >= 50): undeclared repo mods with a trace dated BEFORE the stable 1.22 date
         (2026-04-21) / all undeclared repo mods of the cohort; and the corrected value. Claimed 16 of 809 = 2%, ~4-5%.
    #52  new mods of the 1.22 window (first release on or after 2026-04-21), undeclared repo mods: trace dated on or
         before the day of the mod's first release / all. Claimed 61 of 482 = 13%, ~28% corrected.
    #42  mods created in 2026 with a readable repository: traces (any date) / mods = 169 of 871; corrected; and the
         share that declare (claimed 18%). Corrected estimate claimed 40-45%.
    #50  tipping point: if hidden AI mods are a share h of the "rest" group and update at rate a, while the other
         mods of the rest would update like the declared group (strong form of the objection, rate p), the observed
         rest rate r = h*a + (1-h)*p, so h = (p - r)/(p - a). Computed with a = 0 (all hidden mods abandoned) and
         a = 0.30 (70% abandoned), on the final cohort-1.22 numbers.
  Output: results\hidden-ai-estimate-<extract>.md (aggregates only).
.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File scripts\Get-HiddenAiEstimate.ps1
#>
param(
    [string]$Extract = 'extract-2026-11-02-all',
    [string]$RefDate = '2026-04-21',
    [string]$Cohort = '1.22',
    [int]$MinDownloads = 50,
    [int]$Horizon = 195,
    [string]$Root,
    [string]$DataDir
)
$ErrorActionPreference = 'Stop'
if (-not $Root) { $Root = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..' }
if (-not $DataDir) { $DataDir = Join-Path $Root 'data\private' }
$inv = [Globalization.CultureInfo]::InvariantCulture
function D([string]$s) { [datetime]::ParseExact($s.Trim(), [string[]]@('yyyy-MM-dd HH:mm:ss', 'yyyy-MM-dd'), $inv, 'None') }
function F([double]$x, [string]$f = 'N1') { $x.ToString($f, $inv) }
function Pc($k, $n) { if ($n -eq 0) { '-' } else { '{0}% ({1}/{2})' -f (F (100.0 * $k / $n)), $k, $n } }
$ex = Join-Path $DataDir $Extract
$ref = D $RefDate

$mods = @{}; Import-Csv (Join-Path $ex 'mods.csv') -Encoding UTF8 | ForEach-Object { $mods[$_.modid] = $_ }
$ai = @{}; Import-Csv (Join-Path $ex 'ai-mods.csv') | ForEach-Object { $ai[$_.modid] = $_ }
function IsDecl($id) { $ai[$id] -and $ai[$id].used -eq 'True' }
function IsNoAi($id) { $ai[$id] -and $ai[$id].notUsed -eq 'True' -and $ai[$id].used -ne 'True' }
$mr = @{}; Import-Csv (Join-Path $ex 'stage3\mod-repo-ai.csv') | Where-Object { $_.status -eq 'ok' } | ForEach-Object { $mr[$_.modid] = $_ }
$first = @{}
Import-Csv (Join-Path $ex 'releases.csv') -Encoding UTF8 | ForEach-Object { $d = D $_.created; if (-not $first.ContainsKey($_.modid) -or $d -lt $first[$_.modid]) { $first[$_.modid] = $d } }
$coh = @{}; Import-Csv (Join-Path $ex 'cohort-rows.csv') | Where-Object { $_.release -eq $Cohort -and [int]$_.downloads -ge $MinDownloads } | ForEach-Object { $coh[$_.modid] = $_ }
function Trace($id) { $mr[$id].aiTrace -eq 'yes' }

$md = New-Object Collections.Generic.List[string]
$md.Add("# Hidden AI estimates ($Extract)")
$md.Add('')
$md.Add('Generated by `scripts\Get-HiddenAiEstimate.ps1`. Aggregates only. Definitions in the script header. Repository traces exist only for mods with a readable repository (23% of mods, a more involved group of authors); the traces catch only part of the AI use, hence the sensitivity correction, which is rough by construction.')

# ---- sensitivity ----
$decRepo = @($mr.Keys | Where-Object { IsDecl $_ })
$decTr = @($decRepo | Where-Object { Trace $_ })
$sens = $decTr.Count / $decRepo.Count
$dec26 = @($decRepo | Where-Object { (D $mods[$_].created).Year -eq 2026 }); $dec26Tr = @($dec26 | Where-Object { Trace $_ })
$noRepoTr = @($mr.Keys | Where-Object { (IsNoAi $_) -and (Trace $_) }).Count
$md.Add('')
$md.Add('## Sensitivity of traces (declared mods with a readable repository)')
$md.Add('')
$md.Add("- All years: **$(Pc $decTr.Count $decRepo.Count)** with a trace. This is the ~45% used below (sensitivity s = $(F $sens 'N3')).")
$md.Add("- Only mods created in 2026: $(Pc $dec26Tr.Count $dec26.Count). ""No AI"" mods with a trace: $noRepoTr (should be ~0).")

# ---- #51 ----
$c = @($coh.Keys | Where-Object { $mr.ContainsKey($_) -and -not (IsDecl $_) -and -not (IsNoAi $_) })
$ct = @($c | Where-Object { (Trace $_) -and (D $mr[$_].firstAiDate) -lt $ref })
$cAny = @($c | Where-Object { Trace $_ })
$md.Add('')
$md.Add("## #51: cohort $Cohort, undeclared repo mods, trace dated before the stable release ($RefDate)")
$md.Add('')
$md.Add("- Undeclared repo mods in the cohort (downloads >= $MinDownloads): $($c.Count); with a trace dated before ${RefDate}: **$(Pc $ct.Count $c.Count)**. Claimed: 16 of 809 (2%).")
$md.Add("- Corrected for sensitivity: $(F (100.0 * $ct.Count / $c.Count / $sens)) % (observed / $(F $sens 'N2')). Claimed ~4-5%.")
$md.Add("- With any trace date (look-ahead, not used in the post): $(Pc $cAny.Count $c.Count).")
$md.Add("- Excluding noAI mods is what gives 809; counting them too gives $(@($coh.Keys | Where-Object { $mr.ContainsKey($_) -and -not (IsDecl $_) }).Count) mods and the same 16 traces.")

# ---- #52 ----
$nw = @($mr.Keys | Where-Object { -not (IsDecl $_) -and -not (IsNoAi $_) -and $first.ContainsKey($_) -and $first[$_] -ge $ref })
$nwT = @($nw | Where-Object { (Trace $_) -and (D $mr[$_].firstAiDate).Date -le $first[$_].Date })
$nwAny = @($nw | Where-Object { Trace $_ })
$md.Add('')
$md.Add("## #52: new mods of the $Cohort window (first release on or after $RefDate), undeclared repo mods")
$md.Add('')
$md.Add("- Undeclared repo mods: $($nw.Count); trace dated on or before the day of the first release: **$(Pc $nwT.Count $nw.Count)**. Claimed: 61 of 482 (13%).")
$md.Add("- Corrected: $(F (100.0 * $nwT.Count / $nw.Count / $sens)) %. Claimed ~28%.")
$md.Add("- Any trace date: $(Pc $nwAny.Count $nw.Count); corrected $(F (100.0 * $nwAny.Count / $nw.Count / $sens)) %. Claimed 82 (17%), ~38%.")
$md.Add('- No update horizon is applied (all new mods of the window); a 30 or 90 day horizon would remove the youngest mods.')

# ---- #42 ----
$r26 = @($mr.Keys | Where-Object { (D $mods[$_].created).Year -eq 2026 })
$r26T = @($r26 | Where-Object { Trace $_ }); $r26D = @($r26 | Where-Object { IsDecl $_ })
$r26DT = @($r26D | Where-Object { Trace $_ })
$corr = 100.0 * $r26T.Count / $r26.Count / $sens
$md.Add('')
$md.Add('## #42: mods created in 2026 with a readable repository')
$md.Add('')
$md.Add("- Mods: $($r26.Count); with a trace (any date): **$(Pc $r26T.Count $r26.Count)** (claimed 169 of 871 = 19%); declared: **$(Pc $r26D.Count $r26.Count)** (claimed 18%).")
$md.Add("- Corrected (traces / sensitivity $(F $sens 'N2')): $(F ($r26T.Count / $sens) 'N0') of $($r26.Count) = $(F $corr) % (claimed 40-45%).")
$alt = ($r26D.Count + ($r26T.Count - $r26DT.Count) / $sens) / $r26.Count
$md.Add("- Alternative not used in the post (declared count + undeclared traces / sensitivity; the post's formula applies the sensitivity also to traces of mods that already declare): $(F (100.0 * $alt)) %. With 2026-only sensitivity $(F (100.0 * $dec26Tr.Count / $dec26.Count) 'N0')%: $(F (100.0 * ($r26D.Count + ($r26T.Count - $r26DT.Count) / ($dec26Tr.Count / $dec26.Count)) / $r26.Count)) %.")
$md.Add('- The variants here give 41.8-43.2%, inside the claimed 40-45% but not at its ends (the range itself is not derived by any definition); the post says the estimate is rough, on a biased group (repository owners).')

# ---- #50 ----
$dat = @(Import-Csv (Join-Path $ex 'stage4b\cohort-dating.csv'))
function Upd($r) { $r.updatedDay -ne '' -and [int]$r.updatedDay -le $Horizon }
$cr = @($coh.Values)
$early = @($dat | Where-Object verdict -eq 'early'); $earlyU = @($early | Where-Object { $_.updated -eq 'True' })
$allDec = @($cr | Where-Object { IsDecl $_.modid }); $allDecU = @($allDec | Where-Object { Upd $_ })
$late = @($dat | Where-Object verdict -eq 'late' | ForEach-Object { $_.modid })
$restPlain = @($cr | Where-Object { -not (IsDecl $_.modid) -and -not (IsNoAi $_.modid) })
$restLate = @($restPlain + @($cr | Where-Object { $late -contains $_.modid }))
$restPlainU = @($restPlain | Where-Object { Upd $_ }); $restLateU = @($restLate | Where-Object { Upd $_ })
$md.Add('')
$md.Add("## #50: how much hidden AI would flip the conclusion (cohort $Cohort, final numbers)")
$md.Add('')
$md.Add('h = (p - r) / (p - a): share of the rest that must be hidden AI for the rest to look as it does if the non-hidden rest updated at the declared rate p. a = update rate of hidden AI mods.')
$md.Add('')
$md.Add('| p (declared group) | r (rest) | h if a = 0 (all abandoned) | h if a = 0.30 | h if a = 0.50 |')
$md.Add('|---|---|---|---|---|')
foreach ($row in @(@('AI-early', $earlyU.Count, $early.Count, 'rest + AI-late', $restLateU.Count, $restLate.Count), @('all declared (undated)', $allDecU.Count, $allDec.Count, 'rest (undeclared)', $restPlainU.Count, $restPlain.Count))) {
    $p = $row[1] / $row[2]; $r = $row[4] / $row[5]
    $cells = foreach ($a in 0, 0.3, 0.5) { if ($p -le $r) { 'n/a' } else { (F (100.0 * ($p - $r) / ($p - $a))) + '%' } }
    $md.Add("| $($row[0]): $(Pc $row[1] $row[2]) | $($row[3]): $(Pc $row[4] $row[5]) | $($cells -join ' | ') |")
}
$md.Add('')
$md.Add("Plausible hidden share for comparison (#51): about $(F (100.0 * $ct.Count / $c.Count)) % observed, $(F (100.0 * $ct.Count / $c.Count / $sens)) % corrected, among repo mods only.")

$out = Join-Path $Root "results\hidden-ai-estimate-$Extract.md"
[IO.File]::WriteAllLines($out, $md, (New-Object Text.UTF8Encoding($false)))
$md | ForEach-Object { Write-Output $_ }
