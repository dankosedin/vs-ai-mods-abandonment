<#
.SYNOPSIS
  Stage 3 summary: coverage, AI traces in repositories by declaration group, dating, and update shares by group.

.DESCRIPTION
  Inputs: data\<extract>\mods.csv, releases.csv, ai-mods.csv, cohort-rows.csv (Get-Cohorts.ps1), repo-urls.csv,
  stage3\mod-repo-ai.csv (Find-RepoAiTraces.ps1, run with the same -Sample).
  The groups trace and repo depend on the sample (first -Sample of stage3\order.txt); declared, noAI and norepo are
  taken from the whole extract (they do not need a scanned repository).

  Groups of mods:
    declared   stage 4 label: AI used (any USED)
    noAI       stage 4: says "no AI"
    trace      not declared, AI trace in its repository
    repo       not declared, repository scanned (ok), no trace
    norepo     no repository link
  Tools are read from the evidence column (claude/anthropic, copilot, cursor, codex/openai/chatgpt, gemini/jules, other).

  Update shares:
    cohort 1.22   updated within 195 days of stable 1.22, >= 50 downloads (cohort-rows.csv, as in Get-Cohorts.ps1)
    new mods      first published in window 1.22 (on/after 2026-04-21), a release >= 24 h later within 30 / 90 days,
                  only mods with the full horizon before the list date (as in Get-NewMods.ps1, no threshold)
  Trace dating (mods with a trace): first AI date vs. the mod's first ModDB release and vs. stable 1.22.

  Output: results\repo-ai-<extract>[-sN].md (aggregates only).
#>
param(
    [string]$Extract = 'extract-2026-11-02-all',
    [int]$Sample = 0,
    [string]$ListDate = '2026-11-02',
    [string]$Root,
    [string]$DataDir
)
$ErrorActionPreference = 'Stop'
if (-not $Root) { $Root = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..' }
if (-not $DataDir) { $DataDir = Join-Path $Root 'data\private' }
$inv = [Globalization.CultureInfo]::InvariantCulture
function D([string]$s) { [datetime]::ParseExact($s.Trim(), [string[]]@('yyyy-MM-dd HH:mm:ss', 'yyyy-MM-dd'), $inv, 'None') }
function Pct($a, $b) { if ($b -gt 0) { '{0}% ({1}/{2})' -f [math]::Round(100.0 * $a / $b), $a, $b } else { '-' } }
$ex = Join-Path $DataDir $Extract
$asOf = D $ListDate
$stable122 = D '2026-04-21'

$mods = @{}; Import-Csv (Join-Path $ex 'mods.csv') -Encoding UTF8 | ForEach-Object { $mods[$_.modid] = $_ }
$rel = @{}
Import-Csv (Join-Path $ex 'releases.csv') -Encoding UTF8 | ForEach-Object {
    if (-not $rel[$_.modid]) { $rel[$_.modid] = New-Object Collections.Generic.List[datetime] }; $rel[$_.modid].Add((D $_.created)) }
$lab = @{}; Import-Csv (Join-Path $ex 'ai-mods.csv') | ForEach-Object {
    $lab[$_.modid] = if ($_.used -eq 'True') { 'declared' } elseif ($_.notUsed -eq 'True') { 'noAI' } else { $null } }
$hasUrl = @{}; Import-Csv (Join-Path $ex 'repo-urls.csv') | Where-Object status -eq 'ok' | ForEach-Object { $hasUrl[$_.modid] = 1 }
$mr = @{}; Import-Csv (Join-Path $ex 'stage3\mod-repo-ai.csv') | ForEach-Object { $mr[$_.modid] = $_ }

function Tool([string]$ev) {
    $t = @()
    if ($ev -match '(?i)anthropic|claude') { $t += 'Claude' }
    if ($ev -match '(?i)copilot') { $t += 'Copilot' }
    if ($ev -match '(?i)cursor') { $t += 'Cursor' }
    if ($ev -match '(?i)codex|openai|chatgpt|agents\.md') { $t += 'Codex/OpenAI/AGENTS.md' }
    if ($ev -match '(?i)gemini|jules') { $t += 'Gemini' }
    if (-not $t) { $t += 'other' }
    return $t
}

# group per mod
$grp = @{}
foreach ($id in $mods.Keys) {
    if ($lab[$id] -eq 'declared') { $g = 'declared' }
    elseif ($lab[$id] -eq 'noAI') { $g = 'noAI' }
    elseif ($mr[$id] -and $mr[$id].status -eq 'ok') { $g = if ($mr[$id].aiTrace -eq 'yes') { 'trace' } else { 'repo' } }
    elseif (-not $hasUrl[$id]) { $g = 'norepo' }
    else { continue }   # repo not in sample / not scanned / gone
    $grp[$id] = $g
}
$inSample = @($mr.Values)
$okRepos = @($inSample | Where-Object status -eq 'ok' | Select-Object -ExpandProperty repoKey -Unique)
$md = New-Object Collections.Generic.List[string]
$md.Add("# AI traces in mod repositories ($Extract$(if ($Sample) { ", first $Sample repositories of the shuffled order" }))")
$md.Add('')
$md.Add('Generated by `scripts\Get-RepoAiSummary.ps1`. Aggregates only. Definitions in the script header and in `Find-RepoAiTraces.ps1`.')
$md.Add('')
$md.Add('## Coverage')
$md.Add('')
$repoSt = $inSample | Group-Object repoKey | ForEach-Object { $_.Group[0] }
$md.Add("- Repositories: $(@($repoSt).Count); " + (($repoSt | Group-Object status | ForEach-Object { "$($_.Name) $($_.Count)" }) -join ', ') +
    "; archived $(@($repoSt | Where-Object archived -eq 'True').Count), forks $(@($repoSt | Where-Object fork -eq 'True').Count).")
$md.Add("- Mods in these repositories: $($inSample.Count).")
$tr = @($repoSt | Where-Object aiTrace -eq 'yes')
$md.Add("- Repositories with an AI trace: $(Pct $tr.Count $okRepos.Count) of readable ones; mods: $(Pct @($inSample | Where-Object aiTrace -eq 'yes').Count @($inSample | Where-Object status -eq 'ok').Count).")
$sig = @{}; $tools = @{}
foreach ($r in $tr) { foreach ($s in $r.signals.Split(';')) { $sig[$s] = 1 + [int]$sig[$s] }; foreach ($t in (Tool $r.evidence)) { $tools[$t] = 1 + [int]$tools[$t] } }
$md.Add("- Signals (repositories, one may have several): " + (($sig.Keys | Sort-Object { -$sig[$_] } | ForEach-Object { "$_ $($sig[$_])" }) -join ', ') + '.')
$md.Add("- Tools: " + (($tools.Keys | Sort-Object { -$tools[$_] } | ForEach-Object { "$_ $($tools[$_])" }) -join ', ') + '.')
$md.Add('')
$md.Add('## Traces by declaration (mods with a readable repository)')
$md.Add('')
$md.Add('| declaration on ModDB | mods | with AI trace |')
$md.Add('|---|---|---|')
$okMods = @($inSample | Where-Object status -eq 'ok')
foreach ($g in 'declared', 'noAI', $null) {
    $set = @($okMods | Where-Object { $lab[$_.modid] -eq $g })
    $name = if ($g) { $g } else { 'none' }
    $md.Add("| $name | $($set.Count) | $(Pct @($set | Where-Object aiTrace -eq 'yes').Count $set.Count) |")
}
$md.Add('')
$md.Add('By the year the mod was created (share of mods with a readable repository that have a trace; share of all mods with a repository link):')
$md.Add('')
$md.Add('| created | mods with link (all) | traced (sample) |')
$md.Add('|---|---|---|')
$years = $mods.Values | Group-Object { (D $_.created).Year } | Sort-Object Name
foreach ($y in $years) {
    $all = $y.Group.Count; $wl = @($y.Group | Where-Object { $hasUrl[$_.modid] }).Count
    $s = @($okMods | Where-Object { (D $mods[$_.modid].created).Year -eq [int]$y.Name })
    $md.Add("| $($y.Name) | $(Pct $wl $all) | $(Pct @($s | Where-Object aiTrace -eq 'yes').Count $s.Count) |")
}
$md.Add('')
$md.Add('## Dating of traces (mods with a trace)')
$md.Add('')
$tm = @($okMods | Where-Object aiTrace -eq 'yes')
$before = 0; $sameMonth = 0; $later = 0; $pre122 = 0; $cohortPre = 0; $cohortPost = 0
foreach ($m in $tm) {
    $fa = D $m.firstAiDate
    $r = $rel[$m.modid]; if (-not $r) { continue }
    $fr = ($r | Sort-Object)[0]
    $days = ($fa - $fr.Date).TotalDays
    if ($days -le -1) { $before++ } elseif ($days -le 31) { $sameMonth++ } else { $later++ }
    if ($fa -lt $stable122) { $pre122++ }
    if ($fr -lt $stable122) { if ($fa -lt $stable122) { $cohortPre++ } else { $cohortPost++ } }
}
$md.Add("- First trace vs. first ModDB release: before $before, within 31 days after $sameMonth, later $later (of $($tm.Count)).")
$md.Add("- First trace before stable 1.22: $pre122. Among traced mods published before 1.22: trace before 1.22 $cohortPre, after $cohortPost.")
$md.Add('')
$md.Add('## Update shares by group')
$md.Add('')
$coh = @{}; Import-Csv (Join-Path $ex 'cohort-rows.csv') | Where-Object { $_.release -eq '1.22' -and [int]$_.downloads -ge 50 } | ForEach-Object { $coh[$_.modid] = $_ }
$md.Add('| group | cohort 1.22, 195 d | new mods 1.22, 30 d | new mods 1.22, 90 d |')
$md.Add('|---|---|---|---|')
foreach ($g in 'declared', 'noAI', 'trace', 'trace, dated', 'repo', 'norepo') {
    $dated = $g -eq 'trace, dated'
    $ids = @($grp.Keys | Where-Object { $grp[$_] -eq ($g -replace ', dated', '') })
    $c = @($ids | Where-Object { $coh[$_] })
    if ($dated) { $c = @($c | Where-Object { (D $mr[$_].firstAiDate) -lt $stable122 }) }
    $cu = @($c | Where-Object { $coh[$_].updatedDay -ne '' -and [int]$coh[$_].updatedDay -le 195 })
    $cells = @()
    foreach ($h in 30, 90) {
        $n = 0; $u = 0
        foreach ($id in $ids) {
            $r = $rel[$id]; if (-not $r) { continue }
            $d = @($r | Sort-Object); $f = $d[0]
            if ($dated -and (D $mr[$id].firstAiDate) -gt $f.Date) { continue }
            if ($f -lt $stable122 -or ($asOf - $f).TotalDays -lt $h) { continue }
            $n++
            if ($d | Where-Object { ($_ - $f).TotalHours -ge 24 -and ($_ - $f).TotalDays -le $h }) { $u++ }
        }
        $cells += (Pct $u $n)
    }
    $md.Add("| $g | $(Pct $cu.Count $c.Count) | $($cells[0]) | $($cells[1]) |")
}
$md.Add('')
$md.Add('Groups: declared = AI declared on ModDB; noAI = says no AI; trace = not declared, AI trace in repository (current; a trace dated after the reference point implies commits after it, i.e. a look-ahead bias towards "updated"); trace, dated = only traces dated before the reference point (cohort: stable 1.22; new mods: the day of the first release); repo = not declared, readable repository without trace; norepo = no repository link (whole extract, not sampled). Mods by one author are not independent.')

$suffix = if ($Sample) { "-s$Sample" } else { '' }
$out = Join-Path $Root "results\repo-ai-$Extract$suffix.md"
[IO.File]::WriteAllLines($out, $md, (New-Object Text.UTF8Encoding($false)))
$md -join "`n"
